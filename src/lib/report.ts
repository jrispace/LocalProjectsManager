import type { ProjectData, Registry } from "./types";
import { calcStats } from "./utils";

export function generateMarkdownReport(
  registry: Registry,
  getProjectData: (key: string) => ProjectData | null,
): string {
  const lines: string[] = [];
  const now = new Date().toLocaleString();

  lines.push(`# 📋 LocalProjectsManager — Report`);
  lines.push(`_Generated: ${now}_\n`);
  lines.push(`---\n`);

  // Overview
  let totalTasks = 0;
  let totalDone = 0;
  let totalOverdue = 0;

  const projectSummaries: { name: string; key: string; stats: ReturnType<typeof calcStats>; pct: number }[] = [];

  for (const p of registry.projects) {
    const data = getProjectData(p.key);
    if (!data || !data.phases) continue;
    const s = calcStats(data.phases);
    totalTasks += s.total;
    totalDone += s.done;
    totalOverdue += s.overdue;
    const pct = s.total > 0 ? Math.round((s.done / s.total) * 100) : 0;
    projectSummaries.push({ name: p.name, key: p.key, stats: s, pct });
  }

  const overallPct = totalTasks > 0 ? Math.round((totalDone / totalTasks) * 100) : 0;

  lines.push(`## Overview\n`);
  lines.push(`| Metric | Value |`);
  lines.push(`|--------|-------|`);
  lines.push(`| Total Projects | ${projectSummaries.length} |`);
  lines.push(`| Total Tasks | ${totalTasks} |`);
  lines.push(`| Completed | ${totalDone} |`);
  lines.push(`| Overdue | ${totalOverdue} |`);
  lines.push(`| Progress | **${overallPct}%** |`);
  lines.push(``);

  // Progress bar (ASCII)
  const filled = Math.round(overallPct / 5);
  const empty = 20 - filled;
  lines.push(`\`[${"█".repeat(filled)}${"░".repeat(empty)}]\` ${overallPct}%\n`);
  lines.push(`---\n`);

  // Per-project
  for (const proj of projectSummaries) {
    lines.push(`## ${proj.name}`);
    lines.push(`> ${proj.stats.done}/${proj.stats.total} tasks · ${proj.pct}% · ${proj.stats.overdue} overdue\n`);

    const data = getProjectData(proj.key);
    if (!data?.phases) continue;

    for (const phase of data.phases) {
      if (phase.tasks.length === 0) continue;
      lines.push(`### ${phase.name}`);
      for (const task of phase.tasks) {
        const check = task.done ? "x" : " ";
        const overdue = task.dueDate && new Date(task.dueDate) < new Date() && !task.done ? " ⚠️OVERDUE" : "";
        lines.push(`- [${check}] ${task.text}${overdue}`);
      }
      lines.push(``);
    }

    lines.push(`---\n`);
  }

  // Footer
  lines.push(`\n_Generated by LocalProjectsManager — © JRiSpace_\n`);

  return lines.join("\n");
}

export async function copyReportToClipboard(
  registry: Registry,
  getProjectData: (key: string) => ProjectData | null,
): Promise<void> {
  const md = generateMarkdownReport(registry, getProjectData);
  await navigator.clipboard.writeText(md);
}
