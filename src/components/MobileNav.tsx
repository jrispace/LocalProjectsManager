const NAV_ITEMS = [
  { view: "dashboard", label: "Home", icon: icons.dashboard },
  { view: "mytasks", label: "My Tasks", icon: icons.tasks },
  { view: "crm", label: "CRM", icon: icons.projects },
  { view: "projects", label: "Projects", icon: icons.checklist },
];

export default function MobileNav() {
  const { view, setView, selectProject } = useApp();

  const handleNav = (v: string) => {
    if (v === "projects") {
      selectProject(null);
    } else {
      setView(v as any);
    }
  };

  return (
    <nav className="mobile-nav">
      <div className="mobile-nav-items">
        {NAV_ITEMS.map((item) => (
          <div
            key={item.view}
            className={`mobile-nav-item ${view === item.view ? "active" : ""}`}
            onClick={() => handleNav(item.view)}
          >
            <div className="mobile-nav-icon">{item.icon}</div>
            <span>{item.label}</span>
          </div>
        ))}
      </div>
    </nav>
  );
}
